    #[test]
    fn matches_the_cpp_reference_bit_for_bit() {
        // The fixture is written case-major (all functions for case 0, then
        // case 1, ...), the same order as CASES, so a line's case index is its
        // position divided by the per-case line count.
        let lines: Vec<&str> = reference().lines().collect();
        assert_eq!(lines.len() % CASES.len(), 0, "fixture/case mismatch");
        let per_case = lines.len() / CASES.len();
        for (i, line) in lines.iter().enumerate() {
            let ci = i / per_case;
            let (dn0, up, op, clamp) = &CASES[ci];
            let alpha_sw = ci % 2 != 0;
            let f: Vec<&str> = line.split(' ').collect();
            let name = f[0];
            let mut dn = *dn0;
            call(name, &mut dn, up, *op, alpha_sw, *clamp);
            for ch in 0..4 {
                let want = u64::from_str_radix(f[1 + ch], 16).unwrap();
                assert_eq!(
                    dn[ch].to_bits(),
                    want,
                    "{name} case {ci} channel {ch}: {} != {}",
                    dn[ch],
                    f64::from_bits(want)
                );
            }
        }
    }

