// 19 Cross Dissolve (up/dn both transparent -> show dn)
pub fn cross_dissolve(dn: &mut [f64; 4], up: &[f64; 4], up_opacity: f64, do_clamp: bool) {
    if up[3] <= 0.0 && dn[3] <= 0.0 {
        return;
    }
    dn[0] = cross_dissolve_ch(dn[0], up[0], up_opacity);
    dn[1] = cross_dissolve_ch(dn[1], up[1], up_opacity);
    dn[2] = cross_dissolve_ch(dn[2], up[2], up_opacity);
    dn[3] = cross_dissolve_ch(dn[3], up[3], up_opacity);
    finish(dn, do_clamp);
}

// 20 Subtract
pub fn subtract(
    dn: &mut [f64; 4],
    up: &[f64; 4],
    up_opacity: f64,
    alpha_rendering_sw: bool,
    do_clamp: bool,
) {
    if transparent_guard(dn, up, up_opacity) {
        return;
    }
    dn[0] -= up[0] * up_opacity;
    dn[1] -= up[1] * up_opacity;
    dn[2] -= up[2] * up_opacity;
    if alpha_rendering_sw {
        dn[3] -= up[3] * up_opacity;
    }
    finish(dn, do_clamp);
}

