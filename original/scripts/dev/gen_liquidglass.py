#!/usr/bin/env python3
"""Generate stuff/config/qss/LiquidGlass/LiquidGlass.qss.

Takes the complete Dark theme (same selector coverage as every theme), remaps
its neutral greys onto a blue-slate ramp and its accent blues onto the Liquid
Glass accent, then appends hand-written glass overrides from
scripts/dev/liquidglass_overrides.qss. Solid layered surfaces only: Qt style
sheets cannot blur, so alpha-faked glass is avoided.

    python scripts/dev/gen_liquidglass.py
"""
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "stuff/config/qss/Dark/Dark.qss"
OVR = Path(__file__).with_name("liquidglass_overrides.qss")
DST = REPO / "stuff/config/qss/LiquidGlass/LiquidGlass.qss"

RAMP = [(0, (0x07, 0x0b, 0x11)), (40, (0x16, 0x20, 0x30)), (72, (0x24, 0x32, 0x49)),
        (100, (0x35, 0x44, 0x5f)), (160, (0x8c, 0x9b, 0xb3)),
        (200, (0xd0, 0xda, 0xe8)), (255, (0xff, 0xff, 0xff))]
ACCENT = {  # Dark accent blues -> Liquid Glass accent family
    "#456aa9": "#2a6fb0", "#5b7fbc": "#2f7fc4", "#384760": "#2b4666",
    "#3d5379": "#2f5683", "#39588c": "#2a669f", "#7fdbfc": "#8fe3ff",
}

def ramp(l):
    for (a, ca), (b, cb) in zip(RAMP, RAMP[1:]):
        if l <= b:
            t = (l - a) / (b - a)
            return tuple(round(x + (y - x) * t) for x, y in zip(ca, cb))
    return RAMP[-1][1]

def remap(m):
    h = m.group(0).lower()
    if h in ACCENT:
        return ACCENT[h]
    r, g, b = (int(h[i:i + 2], 16) for i in (1, 3, 5))
    if r == g == b:
        return "#%02x%02x%02x" % ramp(r)
    return h

text = re.sub(r"#[0-9a-fA-F]{6}\b", remap, SRC.read_text())
header = ("/* GENERATED by scripts/dev/gen_liquidglass.py from Dark.qss + "
          "liquidglass_overrides.qss. Edit those, not this file. */\n")
DST.write_text(header + text + "\n" + OVR.read_text())
print("wrote", DST)
