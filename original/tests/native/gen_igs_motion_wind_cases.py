"""Regenerate the motion-wind goldens: the port's reference output.

Records what the *original* `igs_motion_wind_pixel.cpp` + `igs_motion_wind_table.cpp`
(recovered from git history, since the port deletes both) produced for three fixed
configurations driven over a deterministic 400-pixel sequence.

Two goldens, because `unsigned long` is 64-bit on LP64 (macOS, Linux) and 32-bit on
LLP64 (Windows), and the original LCG derives *both* its modulus and its `next_d`
denominator from that width:

    igs_motion_wind_cases.txt       --rng-bits 64   (macOS, Linux)
    igs_motion_wind_cases_32.txt    --rng-bits 32   (Windows x64, i686 Linux)

Both are produced on any POSIX host. The 32-bit one is not a guess: it reruns the
recurrence with a 32-bit word, modulus 2^31 and denominator 2^31-1, which is what the
Windows build of the original actually did. The Rust test picks its golden with
`size_of::<c_ulong>()`, not `cfg(target_os)`, so i686 Linux is covered too.

Do not "fix" the mismatch by widening the Rust RNG to `u64`: the Windows original used
a 32-bit `unsigned long`, and reproducing it is the point.

The reference is compiled against a generated `igs_math_random.h` stub implementing the
LCG at the requested width, so this generator needs no `libflare_formats.a` and runs
with nothing but a host C++ compiler.

Two things to know about how the reference is built:
- Quoted includes resolve relative to the *including* file first, so the archived
  `igs_motion_wind_pixel.cpp` picks up the archived `igs_motion_wind_pixel.h` and the
  generated RNG stub from the temp workdir even though `-I <tree>/stdfx` comes first.
  If `HDRS` ever loses an entry, the live FFI-forwarder header wins instead and the
  class is defined twice (a compile error, not a silent pass) -- keep SRCS and HDRS in
  step.
- The archived sources still include the **live** `igs_ifx_common.h` (for
  `igs::image::rgba` / `igs::color::ref_value`). A future edit there changes what the
  golden records, which is exactly how the Toonz `b,g,r` order bit us -- re-run this
  generator and re-check the port if that header changes.

Usage:
    python tests/native/gen_igs_motion_wind_cases.py [--rng-bits {32,64}] [--check]
"""

from __future__ import annotations

import argparse
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import msvc_reference as ms  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
SRCS = [
    "flare/sources/stdfx/igs_motion_wind_pixel.cpp",
    "flare/sources/stdfx/igs_motion_wind_table.cpp",
]
HDRS = [
    "flare/sources/stdfx/igs_motion_wind_pixel.h",
    "flare/sources/stdfx/igs_motion_wind_table.h",
]
GOLDENS = {
    64: os.path.join(ms.ROOT, "flare", "sources", "stdfx", "igs_motion_wind_cases.txt"),
    32: os.path.join(ms.ROOT, "flare", "sources", "stdfx", "igs_motion_wind_cases_32.txt"),
}
HARNESS = os.path.join(HERE, "igs_motion_wind_ref.cpp")

# Same surface as the real igs_math_random.h (default ctor, seed(), next(), next_d()),
# with the word width and the two derived constants chosen to match the target ABI.
RNG_STUB = """\
#pragma once
#ifndef igs_math_random_h
#define igs_math_random_h

// Generated by gen_igs_motion_wind_cases.py -- do not edit.
// Reproduces igs::math::random at a chosen `unsigned long` width so the golden can be
// recorded for an ABI other than the build host's.
#include <cstdint>

using rng_word = std::uint{bits}_t;
static constexpr rng_word RNG_MAX = {rng_max};

namespace igs {{
namespace math {{
class random {{
public:
  random() : seed_(1) {{}}
  void seed(unsigned long s) {{ seed_ = (rng_word)s; }}
  unsigned long seed() const {{ return (unsigned long)seed_; }}
  long next() {{
    seed_ = (rng_word)(seed_ * (rng_word)1103515245u + (rng_word)12345u);
    return (long)(seed_ % ((rng_word)RNG_MAX + (rng_word)1));
  }}
  double next_d() {{ return (double)next() / (double)RNG_MAX; }}

private:
  rng_word seed_;
}};
}} // namespace math
}} // namespace igs

#endif /* !igs_math_random_h */
"""


def rng_stub(bits: int) -> str:
    return RNG_STUB.format(bits=bits, rng_max=hex((1 << (bits - 1)) - 1))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--rng-bits",
        type=int,
        choices=(32, 64),
        default=64,
        help="width of the C++ `unsigned long` the reference simulates (default: 64)",
    )
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 on drift")
    args = ap.parse_args()

    rev = ms.pre_deletion_revision(SRCS[0])
    stdfx = os.path.join(ms.ROOT, "flare", "sources", "stdfx")
    with tempfile.TemporaryDirectory(prefix="igswind-") as workdir:
        ms.extract(rev, SRCS + HDRS, workdir)
        stub = os.path.join(workdir, "igs_math_random.h")
        with open(stub, "w", encoding="utf-8") as fh:
            fh.write(rng_stub(args.rng_bits))
        fresh = ms.build_and_run_host(
            workdir,
            [os.path.basename(s) for s in SRCS],
            HARNESS,
            include_dirs=[stdfx, workdir],
        )

    return ms.check_or_write(GOLDENS[args.rng_bits], fresh, rev, args.check, count="lines")


if __name__ == "__main__":
    raise SystemExit(main())
