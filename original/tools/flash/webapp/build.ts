export const SERVICE_WORKER = `// Generated by tools/flash/webapp/build.ts -- do not edit.
const CACHE = "flare-flash-webapp-v1";
const ASSETS = ["./", "./index.html", "./app.js"];

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Cache-first: the app is fully static, so this is safe and keeps repeat
// visits offline.
self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET") return;
  e.respondWith(
    caches.match(e.request).then((hit) => hit || fetch(e.request).then((res) => {
      if (res.ok && e.request.url.startsWith(self.location.origin)) {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(e.request, copy));
      }
      return res;
    }))
  );
});
`;

export function build(distDir: string = DIST_DIR): string[] {
  const js = bundle();
  mkdirSync(distDir, { recursive: true });
  writeFileSync(join(distDir, "app.js"), js, "utf8");
  writeFileSync(join(distDir, "index.html"), INDEX_HTML, "utf8");
  writeFileSync(join(distDir, "sw.js"), SERVICE_WORKER, "utf8");
  return ["app.js", "index.html", "sw.js"];
}

const invokedDirectly =
  process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href;
if (invokedDirectly) {
  const written = build();
  for (const f of written) console.log(`  dist/${f}`);
}