// Bundles the Flash web app into tools/flash/webapp/dist for GitHub Pages.
//
// Dependency-free on purpose: pages.yml runs `node build.ts` with no npm
// install step, so this leans on Node's built-in TypeScript type stripping
// (node:module.stripTypeScriptTypes) rather than esbuild/tsc.
//
// Inputs : tools/flash/ts/html5-import.ts, tools/flash/webapp/app.ts
// Outputs: dist/app.js, dist/index.html, dist/sw.js
import { stripTypeScriptTypes } from "node:module";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const WEBAPP_DIR = dirname(fileURLToPath(import.meta.url));
// tools/flash/webapp -> tools/flash -> tools -> repo root
export const REPO_ROOT = join(WEBAPP_DIR, "..", "..", "..");
export const IMPORT_TS = join(REPO_ROOT, "tools", "flash", "ts", "html5-import.ts");
export const APP_TS = join(WEBAPP_DIR, "app.ts");
export const DIST_DIR = join(WEBAPP_DIR, "dist");

/** Type-strip one module and drop its ESM syntax so it can be concatenated. */
export function toPlainJs(source: string, file: string): string {
  let js = stripTypeScriptTypes(source, { mode: "strip", sourceMap: false });
  // Cross-module import: the bundle concatenates both modules into one scope,
  // so the specifier has no meaning here and must go.
  js = js.replace(/^\s*import\s+[^;]*?from\s*["'][^"']+["'];?\s*$/gm, "");
  // `export` on a declaration/expression. `export default` and
  // `export { ... }` have no equivalent in a flat scope either.
  js = js.replace(/^\s*export\s+default\s+/gm, "const __default = ");
  js = js.replace(/^\s*export\s*\{[^}]*\};?\s*$/gm, "");
  js = js.replace(/^\s*export\s+/gm, "");
  if (/^\s*(import|export)\s/m.test(js)) {
    throw new Error(`${file}: an import/export survived bundling`);
  }
  return js.trim() + "\n";
}

export function bundle(): string {
  const importJs = toPlainJs(readFileSync(IMPORT_TS, "utf8"), "html5-import.ts");
  const appJs = toPlainJs(readFileSync(APP_TS, "utf8"), "app.ts");
  // Dependency order: app.js calls parseHtml5 at load time.
  return [
    "// Generated by tools/flash/webapp/build.ts -- do not edit.",
    importJs,
    appJs,
  ].join("\n");
}

