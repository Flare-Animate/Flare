//! Compiles every SVG in `assets/ui/icons` into the program.
//!
//! Adding an icon is dropping a file into that folder: this script finds it, names it after the
//! file, and embeds it. Nothing else needs editing.

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default());
    let icons = manifest.join("../../../assets/ui/icons");
    println!("cargo:rerun-if-changed={}", icons.display());
    let mut names: Vec<(String, PathBuf)> = std::fs::read_dir(&icons)
        .map(|entries| {
            entries
                .filter_map(Result::ok)
                .map(|e| e.path())
                .filter(|p| p.extension().is_some_and(|x| x == "svg"))
                .filter_map(|p| {
                    let name = p.file_stem()?.to_str()?.to_owned();
                    Some((name, p.canonicalize().unwrap_or(p)))
                })
                .collect()
        })
        .unwrap_or_default();
    names.sort();
    let mut table = String::from(
        "/// Every icon: (name, SVG source). Generated by build.rs.\npub static TABLE: &[(&str, &[u8])] = &[\n",
    );
    for (name, path) in &names {
        // Writing to a String cannot fail.
        let _ = writeln!(
            table,
            "    ({name:?}, include_bytes!({:?})),",
            path.display().to_string()
        );
    }
    table.push_str("];\n");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_default()).join("icon_table.rs");
    if let Err(error) = std::fs::write(&out, table) {
        println!("cargo:warning=could not write the icon table: {error}");
    }
}
