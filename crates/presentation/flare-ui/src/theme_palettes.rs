//! The colors of each theme, read by name through the functions in `theme`.

use egui::Color32;

pub(super) struct Palette {
    /// Drawn on egui's light visuals: dark text on pale surfaces.
    pub light: bool,
    pub bg: Color32,
    pub chrome: Color32,
    pub panel: Color32,
    pub panel_raised: Color32,
    pub field: Color32,
    pub faint: Color32,
    pub border: Color32,
    pub border_strong: Color32,
    pub hover: Color32,
    pub text: Color32,
    pub text_strong: Color32,
    pub text_dim: Color32,
    pub text_disabled: Color32,
    pub accent: Color32,
    pub warning: Color32,
    pub stage_surround: Color32,
}

pub(super) const fn rgb(r: u8, g: u8, b: u8) -> Color32 {
    Color32::from_rgb(r, g, b)
}

